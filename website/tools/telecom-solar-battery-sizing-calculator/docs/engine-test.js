"use strict";
const assert = require("assert");
const e = require("../js/engine.js");
const base = { telecomKW: 2.2, telecomHours: 24, transportKW: 0, transportHours: 24, coolingKW: 0, coolingHours: 0, auxKW: 0, auxHours: 0, psh: 4.5, moduleW: 550, systemEfficiencyPct: 80, dustLossPct: 0, tempLossPct: 0, wiringLossPct: 0, controllerLossPct: 0, designMarginPct: 0, modulesPerString: 9, backupHours: 12, rainyDays: 0, systemVoltage: 48, dodPct: 80, batteryEfficiencyPct: 90, batteryMarginPct: 10 };
let r = e.calculate(base);
assert(r.ok);
assert(Math.abs(r.dailyLoad - 52.8) < 1e-6);
assert(Math.abs(r.requiredPV - 14.6666667) < 1e-4);
assert(r.moduleCount === 27);
assert(r.installedModules === 27);
assert(Math.abs(r.installedPV - 14.85) < 1e-9);
assert(r.batteryNominal > 0 && r.batteryAh > 0);
assert(!e.calculate({ telecomKW: 0, psh: 0, moduleW: 550 }).ok);
const stringing = e.calculate({ ...base, modulesPerString: 10, backupHours: 0, batteryMarginPct: 0 });
assert(stringing.moduleCount === 27 && stringing.installedModules === 30 && Math.abs(stringing.installedPV - 16.5) < 1e-9);
const offgrid = e.calculate({ ...base, scenario: 'offgrid' });
assert(offgrid.ok && offgrid.gridSupplement === 0 && offgrid.generatorSupplement >= 0);
const hostile = e.calculate({ ...base, tariff: Infinity, pvCostPerKWp: Infinity, batteryCostPerKWh: Infinity, gridCO2KgPerKWh: Infinity, generatorKWhPerLiter: Infinity, existingPVKWp: Infinity, existingBatteryKWh: Infinity });
assert(hostile.ok && Number.isFinite(hostile.savings) && Number.isFinite(hostile.capex) && Number.isFinite(hostile.co2) && Number.isFinite(hostile.dieselSaved));
const negative = e.calculate({ ...base, tariff: -1, pvCostPerKWp: -1, batteryCostPerKWh: -1, gridCO2KgPerKWh: -1, generatorKWhPerLiter: 0 });
assert(negative.ok && negative.savings === 0 && negative.capex === 0 && negative.co2 === 0 && Number.isFinite(negative.dieselSaved));
assert(!e.calculate({ ...base, psh: Infinity }).ok);
console.log("Telecom solar engine: PASS");

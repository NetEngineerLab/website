const assert=require('assert');
const E=require('../js/engine.js');
let r=E.calculate({referenceBandwidthMbps:100000,interfaces:[{name:'Gi0/0',bandwidthMbps:1000},{name:'Gi0/1',bandwidthMbps:10000},{name:'Lo0',bandwidthMbps:1}]});
assert.strictEqual(r.interfaces[0].cost,100);
assert.strictEqual(r.interfaces[1].cost,10);
assert.strictEqual(r.interfaces[2].cost,65535);
assert.strictEqual(r.totalCost,65645);
r=E.calculate({referenceBandwidthMbps:100000,calculationMode:'floor',interfaces:[{name:'100M',bandwidthMbps:100},{name:'1G',bandwidthMbps:1000}]});
assert.strictEqual(r.interfaces[0].cost,1000);
assert.strictEqual(r.interfaces[1].cost,100);
r=E.calculate({referenceBandwidthMbps:100000,interfaces:[{name:'uplink-a',bandwidthMbps:10000,metricOverride:25},{name:'uplink-b',bandwidthMbps:10000,enabled:false}]});
assert.strictEqual(r.interfaces[0].cost,25);
assert.strictEqual(r.totalCost,25);
assert.ok(r.warnings.includes('manual_metric_override'));
r=E.calculate({referenceBandwidthMbps:100000,paths:[{name:'primary',interfaces:[{name:'a',bandwidthMbps:10000},{name:'b',bandwidthMbps:1000}]},{name:'backup',interfaces:[{name:'c',bandwidthMbps:10000},{name:'d',bandwidthMbps:1000}]},{name:'slow',interfaces:[{name:'e',bandwidthMbps:1000},{name:'f',bandwidthMbps:1000}]}]});
assert.strictEqual(r.bestPathCost,110);
assert.strictEqual(r.ecmpPaths,2);
assert.deepStrictEqual(E.compareReferenceBandwidth({interfaces:[{name:'x',bandwidthMbps:1000}]},[100,1000]).map(x=>x.totalCost),[1,1]);
r=E.calculate({referenceBandwidthMbps:0,interfaces:[{name:'bad',bandwidthMbps:1000}]});
assert.strictEqual(r.status,'invalid');
assert.ok(r.errors.includes('reference_bandwidth_invalid'));
r=E.calculate(); assert.strictEqual(r.referenceBandwidthMbps,100000);
r=E.calculate(null); assert.ok(r.errors.includes('input_type_invalid'));
r=E.calculate([]); assert.ok(r.errors.includes('input_type_invalid'));
r=E.calculate('bad'); assert.ok(r.errors.includes('input_type_invalid'));
r=E.calculate({referenceBandwidthMbps:'100000',interfaces:[{name:'bad',bandwidthMbps:1000}]}); assert.ok(r.errors.includes('reference_bandwidth_invalid'));
r=E.calculate({referenceBandwidthMbps:100000,interfaces:[{name:'bad',bandwidthMbps:'1000'}]}); assert.ok(r.errors.includes('interface_1_bandwidth_invalid'));
console.log('OSPF cost engine: PASS');
